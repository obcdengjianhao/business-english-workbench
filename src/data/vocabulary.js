export async function loadDefaultVocabulary() {
  const [
    { financeWords },
    { projectWords },
    { salesWords },
    { legalWords },
    { meetingWords },
    { managementWords },
    { marketingWords },
    { hrWords },
    { corporateWords },
    { operationsWords },
    { negotiationWords },
    { foodWords },
    { communicationWords },
    { tradeWords },
    { businessWords },
  ] = await Promise.all([
    import('./words_finance.js'),
    import('./words_project.js'),
    import('./words_sales.js'),
    import('./words_legal.js'),
    import('./words_meeting.js'),
    import('./words_management.js'),
    import('./words_marketing.js'),
    import('./words_hr.js'),
    import('./words_corporate.js'),
    import('./words_operations.js'),
    import('./words_negotiation.js'),
    import('./words_food.js'),
    import('./words_communication.js'),
    import('./words_trade.js'),
    import('./words_business.js'),
  ]);

  return [
    ...financeWords,
    ...projectWords,
    ...salesWords,
    ...legalWords,
    ...meetingWords,
    ...managementWords,
    ...marketingWords,
    ...hrWords,
    ...corporateWords,
    ...operationsWords,
    ...negotiationWords,
    ...foodWords,
    ...communicationWords,
    ...tradeWords,
    ...businessWords,
  ].sort((a, b) => a.frequency - b.frequency || a.id - b.id);
}
